// Generates the airline flight-status coverage report from the registry data.
// Deterministic, offline, no network. Run: node scripts/airline-coverage-report.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const DATA = 'packages/airline-directory/data/airlines.json';
const airlines = JSON.parse(readFileSync(DATA, 'utf8')).airlines;

const active = airlines.filter((a) => a.active !== false);
const inactive = airlines.filter((a) => a.active === false);
const deepLink = active.filter((a) => a.statusUrlTemplate);
const statusPage = active.filter((a) => a.flightStatusUrl && !a.statusUrlTemplate);
const homepageOnly = active.filter((a) => !a.flightStatusUrl && !a.statusUrlTemplate);

const row = (a) => `| ${a.name} | ${a.iata ?? ''} | ${a.icao ?? ''} | ${a.country} | ${a.officialDomain} |`;
const sortByName = (list) => [...list].sort((a, b) => a.name.localeCompare(b.name));

const coverage = `# Airline Flight-Status Coverage

Generated by \`scripts/airline-coverage-report.mjs\` from \`${DATA}\`. Do not edit by hand.

## Principles

- **Source of truth: airline-owned domains only.** No aggregators, trackers
  (FlightAware / Flightradar24 / airport boards), agencies, blogs, or encyclopedias.
- **0 flight APIs, 0 paid services, 0 API keys, 0 scraping.** The directory is a
  static, offline-bundled data file with pure lookup code.
- **Accuracy over coverage.** No URL is invented. Where a dedicated status-page
  path is not known with confidence, the entry ships a homepage only and
  resolution stops there — it never falls back to a third-party tracker.
- **Deterministic normalization.** \`BA286\`, \`BA 286\`, \`ba286\`, \`BA-286\` resolve
  identically. Unknown codes return null (no fuzzy matching).

## Resolution levels

1. **deep-link** — official page that targets the exact flight (prefilled).
2. **status-page** — airline's own flight-status page; the traveler pastes the
   flight number (the UI copies it to the clipboard with a toast).
3. **homepage** — airline's official homepage when no status page is on file.

## Summary

| Metric | Count |
|---|---|
| Airlines total | ${airlines.length} |
| Active | ${active.length} |
| Inactive (defunct / merged) | ${inactive.length} |
| Level 1 — deep-link | ${deepLink.length} |
| Level 2 — dedicated status page | ${statusPage.length} |
| Level 3 — homepage only (see unresolved report) | ${homepageOnly.length} |

> Level-1 deep-links and many level-2 paths require **live URL verification** to
> promote. This environment has no network egress, so status paths are populated
> only where the official pattern is well-established and stable; everything else
> is intentionally homepage-only until it can be verified live.

## Level 2 — airlines with a dedicated status page

| Airline | IATA | ICAO | Country | Domain |
|---|---|---|---|---|
${sortByName(statusPage).map(row).join('\n')}

${deepLink.length ? `## Level 1 — deep-link airlines\n\n| Airline | IATA | ICAO | Country | Domain |\n|---|---|---|---|---|\n${sortByName(deepLink).map(row).join('\n')}\n` : ''}
${inactive.length ? `## Inactive airlines (retained, \`active: false\`)\n\n| Airline | IATA | ICAO | Country | Domain |\n|---|---|---|---|---|\n${sortByName(inactive).map(row).join('\n')}\n` : ''}`;

const unresolved = `# Airline Flight-Status — Unresolved (homepage-only)

Generated by \`scripts/airline-coverage-report.mjs\`. Do not edit by hand.

These ${homepageOnly.length} active airlines resolve to their **official homepage**
because a dedicated flight-status page URL is not yet on file with confidence.
This is deliberate: no URL was invented, and no third-party tracker is used as a
fallback. To promote an airline to level 2, add a verified \`flightStatusUrl\`
(airline-owned domain, https) to \`${DATA}\` and re-run \`npm run validate:airlines\`.

| Airline | IATA | ICAO | Country | Domain |
|---|---|---|---|---|
${sortByName(homepageOnly).map(row).join('\n')}
`;

writeFileSync('AIRLINE_STATUS_COVERAGE.md', coverage);
writeFileSync('AIRLINE_STATUS_UNRESOLVED.md', unresolved);
console.log(`Wrote AIRLINE_STATUS_COVERAGE.md and AIRLINE_STATUS_UNRESOLVED.md (${active.length} active, ${statusPage.length} status-page, ${homepageOnly.length} homepage-only).`);
